def measure_mode_power_ag(rho):
    sim = make_sim_tidy(rho)
    task_name = "multiplexer"
    sim_data = web.run(sim, task_name=task_name, folder_name="multiplexer_dlw", verbose=False)
    trans_list = []
    trans_obj = []
    wavelengths = ConfigSim.eval_wvls
    for i in range(len(ConfigSim.eval_wvls)):
        output_amps = sim_data[f"Mode Monitor {wavelengths[i]}"].amps
        amp = output_amps.sel(direction='+', mode_index=0).values
        trans = anp.abs(amp[i]) ** 2
        trans_list.append(trans)
        leaked_trans = anp.sum(anp.abs(amp) ** 2) - anp.abs(amp[i]) ** 2
        avg_leaked_trans = leaked_trans / (len(ConfigSim.eval_wvls) - 1)
        trans_obj.append(trans - avg_leaked_trans)
    trans_obj = np.array(trans_obj)

    return anp.sum(trans_obj**(-ConfigSim.p))**(-1/ConfigSim.p)


@jax.custom_vjp
def measure_mode_power(rho):
    return measure_mode_power_ag(rho)


def measure_mode_power_fwd(rho):
    x, dx = autograd.value_and_grad(measure_mode_power_ag)(anp.array(rho))

    return jnp.array(x), (jnp.array(x), jnp.array(dx))


